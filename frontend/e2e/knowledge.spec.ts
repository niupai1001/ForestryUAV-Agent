import { test, expect } from '@playwright/test';
import { mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

test('explicit Chinese imports retain conflicts, scope and superseded source snapshots', async ({page,baseURL})=>{
  const errors:string[]=[];
  const runId=Date.now().toString(),tag=process.env.FORESTRY_EVIDENCE_TAG||'v1';
  page.on('pageerror',error=>errors.push(error.message));
  const fixture=resolve(`../workspace/knowledge-ui-fixtures-${Date.now()}`);
  mkdirSync(fixture,{recursive:true});
  const sourceA=resolve(fixture,'expert-a.md'),sourceB=resolve(fixture,'expert-b.md');
  const original='合并均值应按记录数加权。适用条件：不同记录数的人工样本。';
  writeFileSync(sourceA,original,'utf8');
  writeFileSync(sourceB,'合并均值不应按记录数加权。适用条件：另一专家意见，本软件夹具未裁定。','utf8');
  await page.goto('/');
  await page.request.get('/session');
  const headers={origin:baseURL!};
  const register=async(path:string,id:string)=>{
    const reply=await page.request.post('/resources/register',{headers,data:{request_id:id,path,classification:'private',read_only:true}});
    expect(reply.ok()).toBe(true);return (await reply.json()).resource_id;
  };
  const a=await register(sourceA,`knowledge-ui-a-${runId}`),b=await register(sourceB,`knowledge-ui-b-${runId}`);
  const create=await page.request.post('/tasks',{headers,data:{request_id:`knowledge-ui-second-task-${runId}`,objective:'第二个任务：核对中文专家意见及条件',
    input_refs:[a,b],harness_mode:'H1',constraints:{allowed_capabilities:['knowledge.search']}}});
  expect(create.status()).toBe(202);const taskId=(await create.json()).task_id;
  await page.reload();
  await page.getByRole('button',{name:'本地知识',exact:true}).click();
  await page.getByRole('combobox',{name:'知识来源',exact:true}).selectOption(a);
  await page.getByLabel('知识来源说明').fill('专家 A');
  await page.getByLabel('知识适用条件').fill('不同记录数的人工样本');
  await page.getByLabel('知识局限').fill('软件测试，未验证科学精度');
  await page.getByRole('button',{name:'明确导入本页／窗口'}).click();
  await expect(page.locator('.knowledge-list')).toContainText('专家 A');
  const old=(await (await page.request.get('/knowledge')).json()).imports.find((value:any)=>value.citation.resource_id===a);
  await page.getByRole('combobox',{name:'知识来源',exact:true}).selectOption(b);
  await page.getByLabel('知识来源说明').fill('专家 B');
  await page.getByLabel('知识适用条件').fill('不同意见，保留冲突');
  await page.getByRole('button',{name:'明确导入本页／窗口'}).click();
  await expect(page.locator('.knowledge-list')).toContainText('专家 B');
  await page.getByRole('combobox',{name:'检索任务',exact:true}).selectOption(taskId);
  await page.getByLabel('中文／英文检索词').fill('合并均值记录数加权');
  await page.getByRole('button',{name:'检索授权知识'}).click();
  const result=page.getByRole('region',{name:'知识检索结果'});
  await expect(result).toContainText('合并均值应按记录数加权');
  await expect(result).toContainText('合并均值不应按记录数加权');
  await expect(result).toContainText('不同意见，保留冲突');
  await result.scrollIntoViewIfNeeded();
  await page.screenshot({path:`../workspace/evidence/knowledge-ui-conflicts-20261010-${tag}.png`,fullPage:true});
  writeFileSync(sourceA,'合并均值：当前版要求先核对记录数，旧版建议已替代。','utf8');
  await page.getByRole('button',{name:'刷新知识来源'}).click();
  const oldRow=page.locator(`[data-import-id="${old.import_id}"]`);
  await expect(oldRow).toContainText('来源已改变，需重新导入');
  await page.getByRole('button',{name:'检索授权知识'}).click();
  await expect(result).not.toContainText('合并均值应按记录数加权');
  await oldRow.getByRole('button',{name:'查看来源快照'}).click();
  await expect(page.getByRole('region',{name:'知识来源快照'}).locator('pre')).toHaveText(original);
  await page.getByRole('button',{name:'收起快照'}).click();
  await page.getByRole('combobox',{name:'知识来源',exact:true}).selectOption(a);
  await page.getByLabel('知识来源说明').fill('专家 A 新版');
  await page.getByRole('button',{name:'明确导入本页／窗口'}).click();
  await expect(oldRow).toContainText('已被新版替代');
  await page.getByRole('button',{name:'检索授权知识'}).click();
  await expect(result).toContainText('当前版要求先核对记录数');
  await expect(result).not.toContainText('合并均值应按记录数加权');
  await page.setViewportSize({width:390,height:844});
  await result.scrollIntoViewIfNeeded();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  await page.screenshot({path:`../workspace/evidence/knowledge-ui-mobile-20261010-${tag}.png`,fullPage:true});
  expect((await (await page.request.get('/memory')).json()).notes).toEqual([]);
  expect(errors).toEqual([]);
});
