import { test, expect } from '@playwright/test';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

test('review fixes: quiet chat, upload ownership, attachments and sealed followup', async ({page}) => {
  test.skip(process.env.RUN_REVIEW_UI!=='1','Only the isolated non-model review fixture.');
  const fixture=JSON.parse(readFileSync(resolve('../workspace/review-ui-20261013-v1/metadata.json'),'utf8'));
  expect(fixture.enable_agent).toBe(false);
  expect(test.info().project.use.baseURL).toBe(fixture.url);
  const errors:string[]=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/');
  await expect(page.locator('.composer')).not.toContainText('公开');
  await expect(page.locator('.guide-card,.local-pill,.task-meta,.context-choice')).toHaveCount(0);
  await expect(page.getByRole('button',{name:'作业',exact:true})).toHaveCount(0);
  await page.getByRole('button',{name:'设置',exact:true}).click();
  const settings=page.getByRole('dialog',{name:'Agent 设置'});
  await settings.getByText('Agent 高级设置',{exact:true}).click();
  await expect(settings.getByRole('combobox',{name:'工作方式',exact:true})).toHaveValue('H2');
  await expect(settings).not.toContainText('公开搜索');
  await settings.getByRole('checkbox',{name:'显示执行诊断面板'}).check();
  await settings.getByRole('button',{name:'关闭设置'}).click();
  await expect(page.getByRole('button',{name:'作业',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'设置',exact:true}).click();
  await settings.getByRole('checkbox',{name:'显示执行诊断面板'}).uncheck();
  await settings.getByRole('button',{name:'关闭设置'}).click();
  await page.getByRole('button',{name:'添加文件',exact:true}).click();
  await expect(page.getByRole('button',{name:'选择大文件引用'})).toBeVisible();
  await expect(page.getByRole('button',{name:'选择目录引用'})).toBeVisible();
  const uploaded=page.waitForResponse(r=>new URL(r.url()).pathname==='/uploads');
  await page.getByLabel('上传文件').setInputFiles({name:'会话自己的.csv',mimeType:'text/csv',buffer:Buffer.from('x,y\n1,2\n')});
  const ref=(await (await uploaded).json()).resource_id;
  await expect(page.getByRole('button',{name:'移除 会话自己的.csv'})).toBeVisible();
  await page.locator('.composer textarea').fill('本轮会话附件界面夹具，不运行模型');
  const creating=page.waitForResponse(r=>new URL(r.url()).pathname==='/tasks'&&r.request().method()==='POST');
  await page.locator('.send-button').click();
  const created=await (await creating).json();
  expect(created.input_refs).toEqual([ref]);
  await expect(page.locator('.user-message')).toContainText(created.objective);
  await page.getByRole('button',{name:'移除 会话自己的.csv'}).click();
  await expect(page.locator('.source-chips')).toHaveCount(0);
  await page.getByRole('button',{name:'新建任务',exact:true}).click();
  await expect(page.locator('.source-chips')).toHaveCount(0);
  await page.getByRole('button',{name:fixture.sealed_task_id,exact:true}).count();
  await page.locator('.history-item').filter({hasText:'已封存的软件界面夹具'}).click();
  await expect(page.locator('.user-message')).toContainText('已封存的软件界面夹具');
  await page.locator('.composer textarea').fill('继续说明刚才报告');
  await expect(page.locator('.send-button')).toBeEnabled();
  const following=page.waitForResponse(r=>new URL(r.url()).pathname===`/tasks/${fixture.sealed_task_id}/messages`);
  await page.locator('.send-button').click();
  expect((await following).status()).toBe(200);
  await expect(page.getByText('继续说明刚才报告',{exact:true})).toBeVisible();
  expect(errors).toEqual([]);
  await page.screenshot({path:resolve('../workspace/evidence/review-ui-20261013.png'),fullPage:true});
  writeFileSync(resolve('../workspace/evidence/review-ui-20261013.json'),JSON.stringify({enable_agent:false,
    status:'passed',created_task_id:created.task_id,sealed_task_id:fixture.sealed_task_id,page_errors:errors},null,2));
});
